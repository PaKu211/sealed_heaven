"""Standalone contract packer, not a simulation-output golden updater.

Uses only Python's struct/hashlib and fixed acceptance-table values. It neither
reads Rust code nor calls sealed_sim. Run with --check to verify the checked-in
reference text; no build outputs or checkpoints are written by this script.
"""
import hashlib
import pathlib
import struct
import sys


def p(fmt, *values):
    return struct.pack("<" + fmt, *values)


def u64(*values):
    return p("Q" * len(values), *values)


def sha(data):
    return hashlib.sha256(data).digest()


H0 = sha(b"SH:C03:EVENT-INIT:v1")


def event(index, tick, actor, kind, payload):
    return p("QQIB", index, tick, actor, kind) + payload


def chain(events):
    digest = H0
    for item in events:
        digest = sha(b"SH:C03:EVENT:v1" + digest + item)
    return digest


def scenario(wake):
    return (u64(wake)
            + b"".join(p("q", 1000 if row == col else 0)
                       for row in range(5) for col in range(5))
            + p("q", -(2**63)) * 5 + u64(1, 1, 1, 1, 2, 1) + p("B", 3) + u64(2))


def table(records):
    return u64(len(records)) + b"".join(records)


def actor(index, task):
    return (p("IBBQ", index, 1, 1, 100) + p("I", 0) * 5
            + p("q", 0) * 6 + u64(1, task) + p("BQIIQQ", 1, 1, 0, 0, 0, 0))


def task(index, stage, due, progress, reservations):
    return (p("QIBQBBBQII", index, index, 0, 0, stage, 0, 1, 1, 0, 0)
            + u64(progress, 0, due, 0, 0, 0)
            + table([u64(r) for r in reservations]) + u64(0))


def stock(index, definition, kind, quantity, owner_kind, owner):
    return p("QQBQBQ", index, definition, kind, quantity, owner_kind, owner)


def checkpoint(wake, tick, actors, cursors, stocks, reservations, tasks, events):
    config = scenario(wake)
    topology = (table([p("QB", 1, 1), p("QB", 2, 0), p("QB", 9, 0)])
                + table([p("QB", 20, 2), p("QB", 30, 4)])
                + table([u64(1, 2, 1, 1), u64(2, 1, 2, 1)])
                + p("QII", 1, 3, 3) + bytes([1, 1, 1, 1, 0, 1, 1, 1, 1]))
    body = (b"SH:C03:STATE" + p("HI", 1, 3) + sha(config)
            + u64(tick, 100, *cursors) + config + table(actors) + topology
            + table(stocks) + table(reservations) + table(tasks)
            + u64(0, 0, 0, 0)  # transactions, registry, pending, traces
            + u64(len(events) + 1) + chain(events))
    return body, body + sha(body)


def vectors():
    result = ["Contract-only C0.3 vectors; generated by docs/tools/c03_vectors.py"]
    def emit(name, events, pair=None):
        result.append(f"{name}.event_stream.sha256={sha(b''.join(events)).hex()}")
        result.append(f"{name}.event_digest={chain(events).hex()}")
        if pair:
            body, blob = pair
            result.append(f"{name}.body.sha256={sha(body).hex()}")
            result.append(f"{name}.blob.sha256={sha(blob).hex()}")

    events = []
    def add(tick, who, kind, payload):
        events.append(event(len(events) + 1, tick, who, kind, payload))
    for who in range(1, 6):
        for offset in range(4):
            add(1, who, 1, u64(21 + 4 * (who - 1) + offset, 101 + offset, 1))
        add(1, who, 7, u64(who) + bytes([2]))
    for who in range(6, 21):
        add(1, who, 2, u64(101, 1) + bytes([4]))
    for who in range(1, 6):
        add(1, who, 7, u64(who) + bytes([4]))
    holds = [p("QQIQQQQB", 21 + 4 * (who - 1) + offset, 101 + offset,
               who, 1, 1, 10, who, 1) for who in range(1, 6) for offset in range(4)]
    image = checkpoint(4, 1, [actor(i, i) for i in range(1, 21)], (21, 41, 1, 105),
                       [stock(101, 3, 2, 5, 3, 1), stock(102, 4, 2, 5, 3, 1),
                        stock(103, 1, 1, 5, 3, 1), stock(104, 5, 2, 5, 3, 1)], holds,
                       [task(i, 4 if i <= 5 else 1, 3 if i <= 5 else 0,
                             1 if i <= 5 else 0,
                             range(21 + 4 * (i - 1), 25 + 4 * (i - 1)) if i <= 5 else [])
                        for i in range(1, 21)], events)
    assert sha(image[1]).hex() == "528bc334bc1f081ccbf06c3247ec46909abd6f1073594dfb13ebd7ae16d640c9"
    emit("M0_T06", events, image)

    events = []
    add(1, 1, 1, u64(2, 1, 1))
    add(1, 1, 7, u64(1) + bytes([4]))
    add(1, 1, 6, bytes([1]) + u64(1, 5) + p("5q", 1000000, 0, 0, 0, 0))
    add(2, 1, 7, u64(1) + bytes([5]))
    add(3, 1, 4, u64(1, 1))
    add(3, 1, 3, u64(2) + bytes([8]))
    add(3, 1, 7, u64(1) + bytes([6]))
    emit("S2_Eat", events)

    events = []
    image = checkpoint(100, 0, [actor(1, 0)], (2, 401, 1, 11),
                       [stock(10, 1, 1, 1, 1, 1)], [], [], [])
    assert sha(image[1]).hex() == "bd803a2c4ae4320ce2a1a5ceb49a2941aec48921c4cbc0a60b15c607b62148c3"
    emit("M0_T07_initial", [], image)
    for hop in range(5):
        add(hop * 2 + 1, 1, 7, u64(401 + hop) + bytes([5]))
        if hop < 4:
            add(hop * 2 + 2, 1, 4, u64(hop + 1, 401 + hop))
            add(hop * 2 + 2, 1, 7, u64(401 + hop) + bytes([6]))
    emit("M0_T07_tick9", events)
    return "\n".join(result) + "\n"


if __name__ == "__main__":
    text = vectors()
    if sys.argv[1:] == ["--check"]:
        reference = pathlib.Path(__file__).resolve().parents[1] / "C0_3_VECTOR_REFERENCE.txt"
        if reference.read_text(encoding="utf-8") != text:
            raise SystemExit("contract reference mismatch")
        print("Contract reference verified (no simulation output used).")
    elif sys.argv[1:]:
        raise SystemExit("usage: c03_vectors.py [--check]")
    else:
        print(text, end="")
